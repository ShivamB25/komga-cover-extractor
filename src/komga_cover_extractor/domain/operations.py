"""Immutable, data-only filesystem intent. A plan never grants authorization."""
from __future__ import annotations

import base64
import json
from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path, PurePosixPath
from typing import Literal, cast

OperationKind = Literal["publish", "move", "quarantine", "mkdir", "rmdir"]


@dataclass(frozen=True, slots=True)
class FileFingerprint:
    root: Path
    relative_path: str
    device: int
    inode: int
    size: int
    mtime_ns: int
    sha256: str

    def __post_init__(self) -> None:
        relative = PurePosixPath(self.relative_path)
        if not self.root.is_absolute() or relative.is_absolute() or any(
            part in {"", ".", ".."} for part in self.relative_path.split("/")
        ) or "\x00" in self.relative_path:
            raise ValueError("fingerprint requires an absolute root and canonical relative path")
        if self.size < 0 or len(self.sha256) != 64 or any(c not in "0123456789abcdef" for c in self.sha256):
            raise ValueError("invalid content fingerprint")

    @property
    def path(self) -> Path:
        return self.root.joinpath(*PurePosixPath(self.relative_path).parts)

    def as_dict(self) -> dict[str, object]:
        return {"root": str(self.root), "relative_path": self.relative_path,
                "device": self.device, "inode": self.inode, "size": self.size,
                "mtime_ns": self.mtime_ns, "sha256": self.sha256}


@dataclass(frozen=True, slots=True)
class RootPermission:
    path: Path
    write: bool = True

    def __post_init__(self) -> None:
        if not self.path.is_absolute():
            raise ValueError("operation roots must be absolute")


@dataclass(frozen=True, slots=True)
class ArtifactSpec:
    """Exactly one observed source or generated byte sequence; never a callable."""
    source: FileFingerprint | None = None
    content: bytes | None = None
    media_type: str | None = None

    def __post_init__(self) -> None:
        if (self.source is None) == (self.content is None):
            raise ValueError("artifact requires exactly one source or content")
        if self.content is not None and not isinstance(self.content, bytes):
            raise ValueError("artifact content must be immutable bytes")

    @property
    def digest(self) -> str:
        if self.source is not None:
            return self.source.sha256
        assert self.content is not None
        return sha256(self.content).hexdigest()

    @property
    def size(self) -> int:
        if self.source is not None:
            return self.source.size
        assert self.content is not None
        return len(self.content)

    def as_dict(self, *, include_content: bool = False) -> dict[str, object]:
        value: dict[str, object] = {
            "source": self.source.as_dict() if self.source else None,
            "sha256": self.digest, "size": self.size, "media_type": self.media_type,
        }
        if include_content and self.content is not None:
            value["content_base64"] = base64.b64encode(self.content).decode("ascii")
        return value


@dataclass(frozen=True, slots=True)
class Operation:
    member_id: str
    kind: OperationKind
    destination: Path
    source: FileFingerprint | None = None
    destination_before: FileFingerprint | None = None
    artifact: ArtifactSpec | None = None
    depends_on: tuple[str, ...] = ()
    collision: Literal["absent", "replace"] = "absent"
    reason: str = ""

    def __post_init__(self) -> None:
        if not self.member_id or any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for c in self.member_id):
            raise ValueError("invalid member identifier")
        if self.kind not in {"publish", "move", "quarantine", "mkdir", "rmdir"}:
            raise ValueError("unsupported operation kind")
        if not self.destination.is_absolute():
            raise ValueError("destination must be absolute")
        if self.kind in {"move", "quarantine"} and self.source is None:
            raise ValueError("source observation required")
        if self.kind == "publish" and self.artifact is None:
            raise ValueError("publication artifact required")
        if self.collision not in {"absent", "replace"}:
            raise ValueError("unknown collision decision")
        if self.collision == "replace" and self.destination_before is None:
            raise ValueError("replacement requires observed prior content")
        if self.destination_before is not None and self.destination_before.path != self.destination:
            raise ValueError("destination observation path mismatch")
        object.__setattr__(self, "depends_on", tuple(self.depends_on))

    def as_dict(self, *, include_content: bool = False) -> dict[str, object]:
        return {
            "member_id": self.member_id, "kind": self.kind,
            "destination": str(self.destination),
            "source": self.source.as_dict() if self.source else None,
            "destination_before": self.destination_before.as_dict() if self.destination_before else None,
            "artifact": self.artifact.as_dict(include_content=include_content) if self.artifact else None,
            "depends_on": list(self.depends_on), "collision": self.collision, "reason": self.reason,
        }


@dataclass(frozen=True, slots=True)
class OperationPlan:
    policy_version: str
    operation_id: str
    operations: tuple[Operation, ...]
    roots: tuple[RootPermission, ...]
    reason: str = ""
    schema_version: int = 1

    def __post_init__(self) -> None:
        if self.schema_version != 1:
            raise ValueError("unsupported operation schema")
        if not self.operation_id or len(self.operation_id) > 128 or any(
            c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for c in self.operation_id
        ):
            raise ValueError("invalid operation identifier")
        if not self.policy_version:
            raise ValueError("policy version required")
        object.__setattr__(self, "operations", tuple(self.operations))
        object.__setattr__(self, "roots", tuple(self.roots))
        seen: set[str] = set()
        destinations: set[Path] = set()
        for member in self.operations:
            if member.member_id in seen or not set(member.depends_on) <= seen:
                raise ValueError("duplicate member or invalid ordered dependencies")
            if member.destination in destinations:
                raise ValueError("duplicate operation destination")
            seen.add(member.member_id)
            destinations.add(member.destination)

    def as_dict(self, *, include_content: bool = False) -> dict[str, object]:
        return {"schema_version": self.schema_version, "policy_version": self.policy_version,
                "operation_id": self.operation_id, "reason": self.reason,
                "roots": [{"path": str(root.path), "write": root.write} for root in self.roots],
                "operations": [op.as_dict(include_content=include_content) for op in self.operations]}


@dataclass(frozen=True, slots=True, init=False)
class PlanReport:
    """A batch result retains intent and hashes, not every generated image buffer."""
    operation_id: str
    _encoded: str

    def __init__(self, plan: OperationPlan):
        object.__setattr__(self, "operation_id", plan.operation_id)
        object.__setattr__(self, "_encoded", json.dumps(plan.as_dict(), ensure_ascii=False))

    def as_dict(self) -> dict[str, object]:
        return cast(dict[str, object], json.loads(self._encoded))
